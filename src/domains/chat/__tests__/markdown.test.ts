import { describe, it, expect } from 'vitest'
import { 한글강조_바로잡기 } from '../markdown'

describe('한글 강조 표시 바로잡기', () => {
    it('닫는 별표 뒤에 조사가 붙어 깨지던 실제 문장을 고친다', () => {
        const 원문 = '메모장에 **"내가 이 책을 꼭 써야겠다고 마음먹은 순간"**을 딱 3줄로'
        expect(한글강조_바로잡기(원문)).toBe('메모장에 "**내가 이 책을 꼭 써야겠다고 마음먹은 순간**"을 딱 3줄로')
    })

    it('홑따옴표와 한글 따옴표도 같이 처리한다', () => {
        expect(한글강조_바로잡기("**'첫 문장'**이")).toBe("'**첫 문장**'이")
        expect(한글강조_바로잡기('**“첫 문장”**이')).toBe('“**첫 문장**”이')
    })

    it('닫는 별표 앞 문장부호를 밖으로 옮긴다', () => {
        expect(한글강조_바로잡기('**꼭 쓰세요.**그리고')).toBe('**꼭 쓰세요**.그리고')
    })

    it('멀쩡한 강조는 건드리지 않는다', () => {
        const 정상 = '이건 **굵게** 나옵니다'
        expect(한글강조_바로잡기(정상)).toBe(정상)
    })

    it('별표가 없으면 그대로 돌려준다', () => {
        const 평문 = '별표 없는 문장입니다'
        expect(한글강조_바로잡기(평문)).toBe(평문)
    })

    it('한 문장에 두 군데가 깨져도 둘 다 고친다', () => {
        const 원문 = '**"앞"**과 **"뒤"**를'
        expect(한글강조_바로잡기(원문)).toBe('"**앞**"과 "**뒤**"를')
    })
})
