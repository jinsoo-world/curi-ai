/**
 * 한글 강조 표시가 깨지는 것을 바로잡는다
 *
 * 실측(2026-09-04, 글담쌤 답변):
 *   메모장에 **"내가 이 책을 꼭 써야겠다고 마음먹은 순간"**을 딱 3줄로
 * → 별표가 글자 그대로 보였다.
 *
 * 마크다운 규칙 때문이다. 닫는 별표 앞이 따옴표(부호)이고 뒤가 글자면
 * 닫는 표시로 인정하지 않는다. 한글은 뒤에 조사가 바로 붙으니
 * (…"**을) 이 조건에 자주 걸린다. 영어는 띄어쓰기라 잘 안 걸린다.
 *
 * 뜻을 바꾸지 않고 따옴표를 별표 밖으로 옮겨 해결한다.
 *   **"X"**을  →  "**X**"을
 */
export function 한글강조_바로잡기(text: string): string {
    if (!text.includes('**')) return text

    return text
        // **"X"** → "**X**"   (겹따옴표·홑따옴표·한글 따옴표)
        .replace(/\*\*(["'“‘])([^*\n]+?)(["'”’])\*\*/g, '$1**$2**$3')
        // **X.** → **X**.     (닫는 별표 앞의 문장부호를 밖으로)
        .replace(/\*\*([^*\n]+?)([.,!?:;])\*\*/g, '**$1**$2')
}
