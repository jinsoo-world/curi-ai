//
// 평소 대화 모델(솔라)에는 검색 도구가 없다. Gemini 에만 구글 검색이 붙어 있다.
// 실측 2026-09-30: 대표가 「리서치 좀 해줘」「instinct 살펴봐줄래?」라고 했는데 봇이 일반론만 말하다가
// 「실시간 검색 기능은 없어요」라고 답했다. 그래서 검색을 부탁하는 말이면 그 한 번만 Gemini(검색 켬)로 보낸다.
// 검색은 비용이 드니 「찾아/검색/리서치/최신/뉴스」처럼 분명히 부탁한 말에만 켠다.

// 「뉴스레터」「검색엔진 최적화」「알아보기 쉽게」「찾아보니까」「최신순」「설문조사」 같은 평범한 말에는 켜지지 않게,
// 부탁하는 끝말(봐 줘, 해 줘, 할래 등)이 붙은 경우만 본다. (코드 검토 0930)
const 봐부탁 = '봐\\s?(?:줘|주|줄)|봐\\?|봐$|볼래'
const SEARCH_WORDS = new RegExp([
    `(?:찾아|알아|살펴)\\s?(?:${봐부탁})`,
    `(?:찾아|살펴)\\s?(?:줘|주세요|줄래)`,
    `(?:검색|(?<!설문|시장)조사|리서치|서치|구글링)\\s?(?:좀\\s?)?(?:해\\s?(?:줘|주|줄|봐)|부탁)`,
    `(?:검색|리서치|서치|구글링)\\s?좀`,
    `(?:검색|리서치|서치|구글링)\\s?해서\\s?(?:알려|정리|찾아)`,
    `(?:최신|최근|요즘)\\s?(?:소식|뉴스|동향)`,
    `뉴스(?!레터).{0,6}(?:알려|찾아|있어|있나|봐)`,
].join('|'))

export function wantsWebSearch(text: string): boolean {
    return SEARCH_WORDS.test(text ?? '')
}

