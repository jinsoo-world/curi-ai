/**
 * 올린 자료에서 남의 개인정보를 가린다 — 대표 지시 2026-09-17 「개인정보나 이런 건 규칙으로」
 *
 * 왜 규칙으로 =  후기 표에는 이름·전화·이메일이 섞여 온다. 사람이 매번 지우고 올리길 바라면 언젠가 샌다.
 *               그래서 올리는 사람이 깜빡해도 **저장되기 전에** 시스템이 가린다.
 *
 * 무엇을 가리나 = 전화번호 · 이메일 · 주민등록번호 · 카드번호 · 계좌로 보이는 긴 숫자
 * 무엇을 안 가리나 = 사람 이름(후기에서 「OO님이 이렇게 말했다」가 통째로 사라지면 쓸모가 없어진다).
 *                  이름까지 지우려면 올리는 분이 표에서 빼야 한다. 화면에 그렇게 적어둔다.
 */

const 규칙: { 무엇: string; 찾기: RegExp; 바꿔 : string }[] = [
    { 무엇: '주민등록번호', 찾기: /\b\d{6}\s?-\s?[1-4]\d{6}\b/g, 바꿔: '[주민번호 가림]' },
    { 무엇: '전화번호', 찾기: /\b01[016789][-.\s]?\d{3,4}[-.\s]?\d{4}\b/g, 바꿔: '[연락처 가림]' },
    { 무엇: '집전화', 찾기: /\b0(2|3[1-3]|4[1-4]|5[1-5]|6[1-4])[-.\s]?\d{3,4}[-.\s]?\d{4}\b/g, 바꿔: '[연락처 가림]' },
    { 무엇: '이메일', 찾기: /\b[\w.+-]+@[\w-]+\.[\w.-]+\b/g, 바꿔: '[메일 가림]' },
    { 무엇: '카드번호', 찾기: /\b\d{4}[-\s]?\d{4}[-\s]?\d{4}[-\s]?\d{4}\b/g, 바꿔: '[카드번호 가림]' },
]

export interface 가린결과 { 글: string; 가린수: Record<string, number>; 합계: number }

export function 개인정보가리기(글: string): 가린결과 {
    let 결과 = 글
    const 가린수: Record<string, number> = {}
    let 합계 = 0

    for (const r of 규칙) {
        const 찾은 = 결과.match(r.찾기)
        if (찾은?.length) {
            가린수[r.무엇] = 찾은.length
            합계 += 찾은.length
            결과 = 결과.replace(r.찾기, r.바꿔)
        }
    }

    return { 글: 결과, 가린수, 합계 }
}
